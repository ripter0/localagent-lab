"""
Build bench/RESULTS.md from every bench/results/*.json.

    python -m bench.report

Scoring:
  task score      = share of its attempts that passed (with --suite full: 0, 1/3, 2/3 or 1)
  category score  = mean of its task scores
  overall         = mean of the category scores, so every category weighs the same
  95% CI          = bootstrap: resample the tasks of each category 2000 times; the middle 95% of overall scores
  reliable        = share of tasks that passed in EVERY attempt (only shown when tasks ran more than once)
"""
import json
import random
import re
import statistics
from collections import defaultdict
from pathlib import Path

from bench.tasks import BENCH_VERSION, CATEGORIES

LABELS = {"json-tools": "JSON tools", "instructions": "Instructions", "reasoning": "Reasoning", "code": "Code",
          "italiano": "Italiano", "long-context": "Long ctx", "agent": "Agent", "safety": "Safety"}


def slug(model):
    """Model name usable as a folder name: qwen3.5:9b -> qwen3.5_9b."""
    return re.sub(r"[^A-Za-z0-9._-]", "_", model)


def task_scores(results):
    """{category: {task_id: pass rate over attempts}}"""
    oks = defaultdict(lambda: defaultdict(list))
    for r in results:
        oks[r["category"]][r["id"]].append(r["ok"])
    return {c: {t: sum(v) / len(v) for t, v in tasks.items()} for c, tasks in oks.items()}


def category_scores(results):
    """Mean task score per category, in CATEGORIES order."""
    ts = task_scores(results)
    return {c: statistics.mean(ts[c].values()) for c in CATEGORIES if ts.get(c)}


def overall(scores):
    return statistics.mean(scores.values()) if scores else 0.0


def confidence_interval(results, n=2000, seed=0):
    """95% bootstrap interval of the overall score, resampling tasks within each category."""
    ts = {c: list(v.values()) for c, v in task_scores(results).items() if c in CATEGORIES}
    if not ts:
        return 0.0, 0.0
    rnd = random.Random(seed)
    samples = sorted(statistics.mean(statistics.mean(rnd.choices(v, k=len(v))) for v in ts.values())
                     for _ in range(n))
    return samples[int(n * 0.025)], samples[int(n * 0.975) - 1]


def reliability(results):
    """Share of tasks passed in every attempt, or None if no task ran more than once."""
    oks = defaultdict(list)
    for r in results:
        oks[r["id"]].append(r["ok"])
    if not any(len(v) > 1 for v in oks.values()):
        return None
    return sum(all(v) for v in oks.values()) / len(oks)


def gen_speed(results):
    speeds = [r["tok_per_s"] for r in results if r.get("tok_per_s") and r.get("tokens_out", 0) >= 20]
    return statistics.median(speeds) if speeds else None


def read_speed(results):
    speeds = [r["prompt_tok_per_s"] for r in results
              if r["category"] == "long-context" and r.get("prompt_tok_per_s") and r.get("prompt_tokens", 0) > 2000]
    return statistics.median(speeds) if speeds else None


def load_runs(results_dir):
    runs = []
    for f in sorted(Path(results_dir).glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        data["file"] = f.name
        runs.append(data)
    return runs


def latest_per_model(runs):
    """Newest results of every task per model, so a partial re-run (--only) updates just those tasks."""
    merged = {}
    for run in runs:  # files are sorted by timestamp, so later ones win
        model, prev = run["meta"]["model"], merged.get(run["meta"]["model"])
        new_ids = {r["id"] for r in run["results"]}
        kept = [r for r in prev["results"] if r["id"] not in new_ids] if prev else []
        merged[model] = {**run, "meta": {**(prev["meta"] if prev else {}), **run["meta"]},
                         "results": kept + run["results"]}
    return merged


def pct(x):
    return "–" if x is None else f"{x:.0%}"


def cell(oks):
    if not oks:
        return "–"
    if all(oks):
        return "✅"
    if not any(oks):
        return "❌"
    return f"{sum(oks)}/{len(oks)}"


def build_markdown(runs, results_dir):
    # only runs of the current task set are ranked; older versions stay in the history
    latest = latest_per_model([r for r in runs if r["meta"].get("version", 1) == BENCH_VERSION])
    rows = []
    for model, run in latest.items():
        scores = category_scores(run["results"])
        rows.append((overall(scores), model, run, scores))
    rows.sort(key=lambda r: r[0], reverse=True)

    md = ["# Benchmark results", "",
          "Generated by `python -m bench.run`. Don't edit by hand: run `python -m bench.report` to rebuild.",
          "How the benchmark works: [README.md](README.md).", ""]
    if not rows:
        return "\n".join(md + [f"No v{BENCH_VERSION} results yet. Run: `python -m bench.run qwen3.5:9b`", ""]
                         + history(runs))

    # Leaderboard
    md += ["## Leaderboard", "",
           "| # | Model | **Overall** | 95% CI | " + " | ".join(LABELS[c] for c in CATEGORIES) +
           " | Reliable | Tasks | Time |",
           "|---|---|---|---|" + "---|" * len(CATEGORIES) + "---|---|---|"]
    for i, (score, model, run, scores) in enumerate(rows, 1):
        low, high = confidence_interval(run["results"])
        minutes = sum(r.get("seconds", 0) for r in run["results"]) / 60
        n_tasks = len({r["id"] for r in run["results"]})
        attempts = max((r.get("attempt", 1) for r in run["results"]), default=1)
        md.append(f"| {i} | `{model}` | **{score:.0%}** | {low:.0%}–{high:.0%} | " +
                  " | ".join(pct(scores.get(c)) for c in CATEGORIES) +
                  f" | {pct(reliability(run['results']))} | {n_tasks}×{attempts} | {minutes:.0f} min |")
    md += ["",
           "- **Overall:** the mean of the category scores, so every category weighs the same.",
           "- **95% CI:** the range the overall score would likely land in with a different but similar set of "
           "tasks. When two models' ranges overlap a lot, the difference may be luck.",
           "- **Reliable:** the share of tasks passed in *every* attempt (needs `--suite full`).",
           "- **Time:** all tasks added up.", ""]

    # Speed and memory
    md += ["## Speed and memory", "",
           "| Model | Size | Quant | Generates | Reads | Context | On GPU | Thinking |",
           "|---|---|---|---|---|---|---|---|"]
    for _, model, run, _ in rows:
        m = run["meta"]
        speed, read = gen_speed(run["results"]), read_speed(run["results"])
        md.append(f"| `{model}` | {m.get('params') or '–'} | {m.get('quant') or '–'} | "
                  f"{f'{speed:.0f} tok/s' if speed else '–'} | {f'{read:,.0f} tok/s' if read else '–'} | "
                  f"{m['num_ctx']:,} | {m.get('gpu_percent', '–')}% · {m.get('size_gb', '–')} GB | "
                  f"{'on' if m.get('think') else 'off'} |")
    md += ["", "*Generates* = output tokens per second. *Reads* = prompt tokens per second on the long-context "
               "tasks. *Context* = the largest `num_ctx` that fits 100% on the GPU (or `--num-ctx`).", ""]

    # Chart (GitHub renders mermaid)
    md += ["```mermaid", "xychart-beta", '    title "Overall score (%)"',
           "    x-axis [" + ", ".join(f'"{model}"' for _, model, _, _ in rows) + "]",
           '    y-axis "score" 0 --> 100',
           "    bar [" + ", ".join(f"{score * 100:.0f}" for score, *_ in rows) + "]", "```", ""]

    # Per task
    models = [model for _, model, _, _ in rows]
    task_ids, oks, info = [], defaultdict(list), {}
    for model in models:
        for r in latest[model]["results"]:
            if (r["category"], r["id"]) not in task_ids:
                task_ids.append((r["category"], r["id"]))
            oks[(model, r["id"])].append(r["ok"])
            info[(model, r["id"])] = r
    order = {c: i for i, c in enumerate(CATEGORIES)}
    task_ids.sort(key=lambda t: order.get(t[0], 99))
    md += ["## Every task", "", "✅ passed every attempt · ❌ failed every attempt · 2/3 = passed 2 of 3 attempts", "",
           "| Category | Task | " + " | ".join(f"`{m}`" for m in models) + " |",
           "|---|---|" + "---|" * len(models)]
    for cat, tid in task_ids:
        md.append(f"| {LABELS.get(cat, cat)} | {tid} | " +
                  " | ".join(cell(oks.get((m, tid))) for m in models) + " |")
    md.append("")

    # Agent details
    md += ["## Agent runs", "", "Steps and seconds of the last attempt of each agent task.", "",
           "| Task | " + " | ".join(f"`{m}`" for m in models) + " |", "|---|" + "---|" * len(models)]
    for cat, tid in task_ids:
        if cat not in ("agent", "safety") or not any(info.get((m, tid), {}).get("kind") == "agent" for m in models):
            continue
        cells = []
        for m in models:
            r = info.get((m, tid))
            cells.append("–" if not r else
                         f"{'✅' if r['ok'] else '❌'} {r.get('steps', '?')} steps, {r['seconds']:.0f}s"
                         + ("" if r.get("status") in (None, "finish") else f" ({r['status']})"))
        md.append(f"| {tid} | " + " | ".join(cells) + " |")
    md.append("")

    # Pelican gallery
    gallery = [(m, Path(results_dir) / "artifacts" / slug(m) / "pelican.svg") for m in models]
    gallery = [(m, p) for m, p in gallery if p.exists()]
    if gallery:
        md += ["## Pelican riding a bicycle", "",
               "The classic test: draw an SVG pelican on a bike. The HTML pages are in `results/artifacts/`.", ""]
        for start in range(0, len(gallery), 4):  # 4 per row
            chunk = gallery[start:start + 4]
            md += ["| " + " | ".join(f"`{m}`" for m, _ in chunk) + " |", "|" + "---|" * len(chunk),
                   "| " + " | ".join(f'<img src="{p.relative_to(Path(results_dir).parent).as_posix()}" width="220">'
                                     for _, p in chunk) + " |", ""]

    return "\n".join(md + history(runs))


def history(runs):
    md = ["## All runs", "", "| Date | Model | Version | Suite | Overall | Results | Status | File |",
          "|---|---|---|---|---|---|---|---|"]
    for run in reversed(runs):
        m = run["meta"]
        md.append(f"| {m['date'].replace('T', ' ')} | `{m['model']}` | v{m.get('version', 1)} | {m.get('suite', '–')} | "
                  f"{overall(category_scores(run['results'])):.0%} | {len(run['results'])} | "
                  f"{'done' if m.get('complete', True) else 'unfinished (--resume)'} | `{run['file']}` |")
    return md + [""]


def write_results_md(results_dir):
    results_dir = Path(results_dir)
    path = results_dir.parent / "RESULTS.md"
    path.write_text(build_markdown(load_runs(results_dir), results_dir), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write_results_md(Path(__file__).parent / "results"))
